"""Offline provider that returns schema-valid canned data.

This exists so the whole application -- upload, Stage 0, Stage 1 across several
vendors, Stage 2, PDF render, resume -- can be exercised with no API key and no
network. It is what the test suite runs against, and what ``LLM_PROVIDER=fake``
selects for a UI walkthrough.

Output is generated *from the schema*, so it stays valid automatically as the
models in ``models.py`` evolve.
"""

from __future__ import annotations

import re
from typing import Any

# The pipeline emits these markers in its prompts (they double as clear
# delimiters for real models); the fake provider reads them back so its output
# lines up with the actual questionnaire and vendor under evaluation.
_QUESTION_RE = re.compile(r"^- id:\s*(\S+)\s*\|\s*category:\s*([^|\n]+)", re.MULTILINE)
_VENDOR_RE = re.compile(r"<vendor>(.*?)</vendor>", re.DOTALL)
_CRITERIA_RE = re.compile(r"<criteria>(.*?)</criteria>", re.DOTALL)

_RATINGS = ["Strong", "Adequate", "Adequate", "Weak"]


class FakeProvider:
    """Deterministic, schema-driven stand-in for a real model."""

    name = "fake"

    def __init__(self, **_ignored):
        self.calls: list[dict[str, Any]] = []

    # ------------------------------------------------------------------

    def complete_json(
        self,
        *,
        system: str,
        user: str,
        schema: dict[str, Any],
        model: str,
        max_tokens: int,
        stage: str,
        cache_system: bool = False,
    ) -> dict[str, Any]:
        self.calls.append({"stage": stage, "model": model, "chars": len(user)})

        questions = _QUESTION_RE.findall(user)
        vendor_match = _VENDOR_RE.search(user)
        vendor = vendor_match.group(1).strip() if vendor_match else "Sample Vendor"
        vendors = [v.strip() for v in vendor.split("||") if v.strip()] or ["Sample Vendor"]
        categories = _unique([c.strip() for _, c in questions])
        if not categories:
            # Stage 1 assessment and Stage 2 pass the criteria list directly
            # rather than the full question list.
            criteria = _CRITERIA_RE.search(user)
            if criteria:
                categories = _unique(
                    [
                        line.strip().lstrip("-").strip()
                        for line in criteria.group(1).splitlines()
                    ]
                )
        categories = categories or ["General"]

        context = _Context(
            stage=stage, questions=questions, vendors=vendors, categories=categories
        )
        return _build(schema, context)

    def count_tokens(self, text: str, *, model: str) -> int:
        return int(len(text) / 3.0) + 1


def _unique(values: list[str]) -> list[str]:
    seen: list[str] = []
    for v in values:
        if v and v not in seen:
            seen.append(v)
    return seen


class _Context:
    """Everything the generator knows about the call it is faking."""

    def __init__(self, stage: str, questions: list, vendors: list[str], categories: list[str]):
        self.stage = stage
        self.questions = questions
        self.vendors = vendors
        self.categories = categories
        self.primary = vendors[0]


def _build(schema: dict[str, Any], ctx: _Context, key: str = "") -> Any:
    """Generate a value satisfying ``schema``, steered by the field name."""
    if "enum" in schema:
        return schema["enum"][0]

    schema_type = schema.get("type")

    if schema_type == "object":
        props: dict[str, Any] = schema.get("properties", {})
        return {name: _build(sub, ctx, name) for name, sub in props.items()}

    if schema_type == "array":
        return _build_array(schema, ctx, key)

    if schema_type == "integer":
        return 3  # mid-scale score
    if schema_type == "number":
        return 3.0
    if schema_type == "boolean":
        return True

    return _build_string(ctx, key)


def _build_array(schema: dict[str, Any], ctx: _Context, key: str) -> list:
    item_schema = schema.get("items", {"type": "string"})

    # Arrays whose length should track real data rather than being arbitrary.
    if key == "questions":
        return [
            {
                "id": f"Q{i}",
                "category": ctx.categories[i % len(ctx.categories)],
                "text": f"Sample question {i} generated by the fake provider.",
                "required": True,
            }
            for i in range(1, 6)
        ]

    if key == "answers":
        ids = [qid for qid, _ in ctx.questions] or ["Q1", "Q2", "Q3"]
        cats = [c for _, c in ctx.questions] or ["General"] * len(ids)
        return [
            {
                "question_id": qid,
                "status": "answered" if i % 4 else "partial",
                "answer_text": (
                    f"{ctx.primary} describes its approach to "
                    f"{cats[i].strip().lower()} in response to {qid}."
                ),
                "verbatim_quote": f"We provide comprehensive {cats[i].strip().lower()} coverage.",
                "confidence": "high" if i % 3 else "medium",
                "source_locator": f"p. {i + 1}",
            }
            for i, qid in enumerate(ids)
        ]

    if key == "per_vendor":
        return [
            {
                "vendor_name": v,
                "pros": [f"{v} answered the questionnaire thoroughly.", "Clear pricing model."],
                "cons": [f"{v} gave limited detail on implementation timeline."],
                "red_flags": [] if i else ["No named security contact provided."],
            }
            for i, v in enumerate(ctx.vendors)
        ]

    if key == "comparison":
        return [
            {
                "criterion": category,
                "cells": [
                    {
                        "vendor_name": v,
                        "assessment": f"{v}: documented approach to {category.lower()}.",
                        "rating": _RATINGS[(i + j) % len(_RATINGS)],
                    }
                    for j, v in enumerate(ctx.vendors)
                ],
            }
            for i, category in enumerate(ctx.categories)
        ]

    if key == "cells":
        return [
            {
                "vendor_name": v,
                "assessment": f"{v}: adequate coverage.",
                "rating": _RATINGS[j % len(_RATINGS)],
            }
            for j, v in enumerate(ctx.vendors)
        ]

    if key == "scores":
        return [
            {
                "category": category,
                "score": 3 + (i % 3) - 1,
                "justification": f"{ctx.primary} addressed {category.lower()} with some detail.",
            }
            for i, category in enumerate(ctx.categories)
        ]

    if key == "findings":
        kinds = ["strength", "weakness", "gap", "red_flag"]
        return [
            {
                "kind": kinds[i % len(kinds)],
                "category": ctx.categories[i % len(ctx.categories)],
                "description": f"Fake {kinds[i % len(kinds)]} observed for {ctx.primary}.",
                "severity": ["low", "medium", "high"][i % 3],
                "evidence": "Quoted from the vendor response.",
            }
            for i in range(4)
        ]

    # Generic short list.
    return [_build(item_schema, ctx, key) for _ in range(2)]


def _build_string(ctx: _Context, key: str) -> str:
    vendor_list = ", ".join(ctx.vendors)
    canned = {
        "rfp_name": "Sample RFP (fake provider)",
        "parsed_by": "llm",
        "vendor_name": ctx.primary,
        "executive_summary": (
            f"This is placeholder output from the fake provider. Responses from "
            f"{vendor_list} were compared across {len(ctx.categories)} criteria. "
            "Set LLM_PROVIDER=anthropic or openai for a real evaluation."
        ),
        "summary": (
            f"{ctx.primary} submitted a complete response covering "
            f"{len(ctx.categories)} categories. Placeholder text from the fake provider."
        ),
        "rationale": (
            f"{ctx.primary} scored highest on the criteria derived from the "
            "questionnaire. Placeholder rationale from the fake provider."
        ),
        "runner_up": ctx.vendors[1] if len(ctx.vendors) > 1 else "",
        "criterion": ctx.categories[0],
        "category": ctx.categories[0],
        "rating": "Adequate",
        "justification": "Placeholder justification from the fake provider.",
        "assessment": "Placeholder assessment.",
        "evidence": "Placeholder evidence quote.",
        "description": "Placeholder finding description.",
        "question_id": "Q1",
        "id": "Q1",
        "text": "Placeholder question text.",
        "answer_text": "Placeholder answer text.",
        "verbatim_quote": "Placeholder verbatim quote.",
        "source_locator": "p. 1",
        "source_file": "",
        "model": "fake",
    }
    return canned.get(key, f"Placeholder {key or 'value'} from the fake provider.")
